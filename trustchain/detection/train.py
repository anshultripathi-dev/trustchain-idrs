"""Train + evaluate the ML models on simulated smart-home traffic.

NOTE: the data is synthetic (generated by trustchain.sim.profiles). Reported numbers
describe behaviour on that simulator, not on a real household.
"""
from __future__ import annotations

import json
import os
import time
from typing import Any

import numpy as np
from sklearn.ensemble import IsolationForest, RandomForestClassifier
from sklearn.metrics import classification_report, confusion_matrix

from ..sim.profiles import PROFILES, TRAFFIC_ATTACKS, apply_attack, normal_sample, profiles_signature
from .baseline import Baseline, warm_baseline
from .features import FEATURES, extract
from .ml import CLASSES, CLF_CONFIDENCE, ModelBundle
from .rules import static_rules

STEP_MIN = 5.0
EP_LEN = 18


def _normal_run(baseline: Baseline, kind: str, rng: np.random.Generator, days: int):
    prof = PROFILES[kind]
    X, hours, samples = [], [], []
    ticks = int(days * 24 * 60 / STEP_MIN)
    for i in range(ticks):
        hour = ((i * STEP_MIN) / 60.0) % 24
        s = normal_sample(prof, hour, rng)
        v, _ = extract(baseline, kind, hour, s)
        X.append(v); hours.append(hour); samples.append(s)
    return np.array(X), hours, samples


def _episodes(baseline: Baseline, rng: np.random.Generator, per_class: int):
    eps = []
    for kind, prof in PROFILES.items():
        for atk in TRAFFIC_ATTACKS:
            for _ in range(per_class):
                start = rng.uniform(0, 24)
                X, samples = [], []
                for t in range(EP_LEN):
                    hour = (start + t * STEP_MIN / 60.0) % 24
                    s = apply_attack(normal_sample(prof, hour, rng), atk, prof, hour, rng)
                    v, _ = extract(baseline, kind, hour, s)
                    X.append(v); samples.append(s)
                eps.append({"kind": kind, "attack": atk, "X": np.array(X), "samples": samples})
    return eps


def _confirmed_first_hit(flags_rule: list[bool], flags_ml: list[bool], need: int = 2) -> int | None:
    streak = 0
    for i, (r, m) in enumerate(zip(flags_rule, flags_ml)):
        streak = streak + 1 if m else 0
        if r or streak >= need:
            return i
    return None


def evaluate(bundle: ModelBundle, test_normal: list[tuple[np.ndarray, list[dict]]], episodes: list[dict]) -> dict[str, Any]:
    thr = bundle.threshold
    detectors = {
        "static_rules": lambda rules, sc: (bool(rules), False),
        "isolation_forest": lambda rules, sc: (False, sc["if_anomaly"]),
        "hybrid": lambda rules, sc: (bool(rules), sc["if_anomaly"] or sc["cls_attack"]),
    }
    result: dict[str, Any] = {}
    # false-positive rate on clean traffic
    norm_scores = []
    for X, samples in test_normal:
        norm_scores.append((bundle.score_batch(X), [static_rules(s) for s in samples]))
    for name, fn in detectors.items():
        tick_fp = confirmed_fp = total = 0
        for scores, rules in norm_scores:
            fr, fm = [], []
            for sc, ru in zip(scores, rules):
                r, m = fn(ru, sc)
                fr.append(r); fm.append(m)
            total += len(scores)
            tick_fp += sum(1 for a, b in zip(fr, fm) if a or b)
            streak = 0
            for a, b in zip(fr, fm):
                streak = streak + 1 if b else 0
                if a or streak >= 2:
                    confirmed_fp += 1
        per_class: dict[str, dict[str, float]] = {}
        for atk in TRAFFIC_ATTACKS:
            sel = [e for e in episodes if e["attack"] == atk]
            tick_hit = tick_n = ep_hit = 0
            lat = []
            for e in sel:
                scores = bundle.score_batch(e["X"])
                fr, fm = [], []
                for sc, s in zip(scores, e["samples"]):
                    r, m = fn(static_rules(s), sc)
                    fr.append(r); fm.append(m)
                tick_n += len(fr)
                tick_hit += sum(1 for a, b in zip(fr, fm) if a or b)
                first = _confirmed_first_hit(fr, fm)
                if first is not None:
                    ep_hit += 1
                    lat.append(first)
            per_class[atk] = {
                "tick_recall": round(tick_hit / max(tick_n, 1), 4),
                "episode_recall": round(ep_hit / max(len(sel), 1), 4),
                "mean_latency_ticks": round(float(np.mean(lat)), 2) if lat else None,
            }
        macro = float(np.mean([v["episode_recall"] for v in per_class.values()]))
        result[name] = {
            "false_positive_rate_tick": round(tick_fp / max(total, 1), 5),
            "false_positive_rate_confirmed": round(confirmed_fp / max(total, 1), 5),
            "episode_recall_macro": round(macro, 4),
            "per_attack": per_class,
        }
    return result


def train_and_evaluate(seed: int = 7, normal_days: int = 6, per_class: int = 4, verbose: bool = False) -> ModelBundle:
    t0 = time.time()
    rng_base = np.random.default_rng(seed)
    baseline = Baseline()
    for kind, prof in PROFILES.items():
        warm_baseline(baseline, kind, prof, 10, np.random.default_rng(rng_base.integers(1 << 30)), STEP_MIN)

    # ---- training data ---------------------------------------------------------------
    rng_tr = np.random.default_rng(seed + 1)
    Xn_list = []
    for kind in PROFILES:
        X, _, _ = _normal_run(baseline, kind, rng_tr, normal_days)
        Xn_list.append(X)
    Xn = np.vstack(Xn_list)
    eps_tr = _episodes(baseline, rng_tr, per_class * 2)
    Xa = np.vstack([e["X"] for e in eps_tr])
    ya = np.array([e["attack"] for e in eps_tr for _ in range(len(e["X"]))])

    n_val = len(Xn) // 5
    perm = rng_tr.permutation(len(Xn))
    X_fit, X_val = Xn[perm[n_val:]], Xn[perm[:n_val]]
    iforest = IsolationForest(n_estimators=300, contamination="auto", random_state=seed).fit(X_fit)
    threshold = float(np.percentile(iforest.decision_function(X_val), 0.5))

    Xc = np.vstack([X_fit, Xa])
    yc = np.concatenate([np.array(["NORMAL"] * len(X_fit)), ya])
    clf = RandomForestClassifier(n_estimators=200, max_depth=12, class_weight="balanced", random_state=seed, n_jobs=-1).fit(Xc, yc)
    bundle = ModelBundle(iforest, clf, threshold)

    # ---- held-out evaluation ---------------------------------------------------------
    rng_te = np.random.default_rng(seed + 100)
    test_normal = []
    for kind in PROFILES:
        X, _, samples = _normal_run(baseline, kind, rng_te, 4)
        test_normal.append((X, samples))
    eps_te = _episodes(baseline, rng_te, per_class * 3)
    comparison = evaluate(bundle, test_normal, eps_te)

    Xt = np.vstack([e["X"] for e in eps_te])
    yt = np.array([e["attack"] for e in eps_te for _ in range(len(e["X"]))])
    Xtn = np.vstack([x for x, _ in test_normal])
    X_all = np.vstack([Xtn, Xt])
    y_all = np.concatenate([np.array(["NORMAL"] * len(Xtn)), yt])
    y_pred = clf.predict(X_all)
    labels = [c for c in CLASSES if c in set(clf.classes_)]
    rep = classification_report(y_all, y_pred, labels=labels, output_dict=True, zero_division=0)
    cm = confusion_matrix(y_all, y_pred, labels=labels)
    sc_norm = iforest.decision_function(Xtn)
    sc_att = iforest.decision_function(Xt)
    lo, hi = float(min(sc_norm.min(), sc_att.min())), float(max(sc_norm.max(), sc_att.max()))
    bins = np.linspace(lo, hi, 25)
    metrics = {
        "trained_at": time.time(),
        "profiles_sig": profiles_signature(),
        "profile_kinds": sorted(PROFILES),
        "data": "synthetic simulator traffic (not real household data)",
        "seconds": round(time.time() - t0, 1),
        "features": FEATURES,
        "samples": {"train_normal": int(len(X_fit)), "train_attack": int(len(Xa)), "test_normal": int(len(Xtn)), "test_attack": int(len(Xt))},
        "if_threshold": round(threshold, 4),
        "clf_confidence_threshold": CLF_CONFIDENCE,
        "comparison": comparison,
        "classifier": {
            "accuracy": round(float((y_all == y_pred).mean()), 4),
            "report": {k: {m: round(float(v), 4) for m, v in rep[k].items()} for k in labels},
            "labels": labels,
            "confusion": cm.tolist(),
            "importances": {f: round(float(i), 4) for f, i in zip(FEATURES, clf.feature_importances_)},
        },
        "score_hist": {
            "edges": [round(float(b), 4) for b in bins],
            "normal": np.histogram(sc_norm, bins)[0].tolist(),
            "attack": np.histogram(sc_att, bins)[0].tolist(),
            "threshold": round(threshold, 4),
        },
    }
    bundle.metrics = metrics
    if verbose:
        print(json.dumps({k: metrics[k] for k in ("seconds", "samples", "if_threshold")}, indent=2))
    return bundle


def ensure_model(model_dir: str, retrain: bool = False) -> ModelBundle:
    path = os.path.join(model_dir, "intrusion_model.joblib")
    if not retrain:
        b = ModelBundle.load(path)
        # a model trained on a different set of device profiles is stale -> retrain
        if b and b.metrics.get("profiles_sig") == profiles_signature():
            return b
    b = train_and_evaluate()
    b.save(path)
    with open(os.path.join(model_dir, "metrics.json"), "w") as fh:
        json.dump(b.metrics, fh, indent=2)
    return b
